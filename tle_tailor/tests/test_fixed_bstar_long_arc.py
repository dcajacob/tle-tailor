"""Authored noiseless GPS control; no historical flight data are required.

The real GPS fixture spans 3.11458 fitting days and about 52.8 subsequent days.
This keeps that grid and the original fixed-six-parameter 1e-4 weighted target,
while asking only the scientifically representable question: recover an orbit
which was generated by the same native SGP4 model class with B* truly fixed.
It does not claim that a real precise ephemeris is exactly an SGP4 trajectory.
"""
from datetime import datetime, timezone

import numpy as np
import pandas as pd
import pytest
from sgp4.api import Satrec, WGS72
from sgp4.conveniences import jday_datetime
from sgp4.model import wgs72

from tle_tailor.fitting.fixed_bstar import fit_fixed_bstar


def native_states(model, offsets_minutes):
    states = []
    for offset in offsets_minutes:
        error, position, velocity = model.sgp4_tsince(float(offset))
        assert error == 0
        states.append((position, velocity))
    states = np.asarray(states)
    assert np.isfinite(states).all()
    return states


@pytest.mark.integration
def test_fixed_bstar_recovers_noiseless_gps_over_original_long_grid_and_target():
    fit_count, holdout_count, cadence_seconds = 300, 5068, 900
    fixed_bstar, original_target = 1e-4, 1e-4
    times = pd.date_range(datetime(2020, 1, 1, tzinfo=timezone.utc),
                          periods=fit_count + holdout_count, freq='900s')
    assert (times[fit_count - 1] - times[0]).total_seconds() == 269100
    epoch = times[fit_count - 1].to_pydatetime()
    jd, fraction = jday_datetime(epoch)
    source = Satrec()
    # Synthetic WGS72 mean elements authored for this control, not copied from
    # the historical satellite: a=26560 km, e=.005, i=55, node=40, argp=45, M=20 deg.
    source.sgp4init(WGS72, 'i', 99999, round(jd + fraction - 2433281.5, 8),
                    fixed_bstar, 0., 0., .005, np.radians(45.), np.radians(55.),
                    np.radians(20.), np.sqrt(wgs72.mu / 26560.**3) * 60., np.radians(40.))
    source.jdsatepochF = fraction
    offsets = np.asarray((times - times[fit_count - 1]).total_seconds()) / 60.
    truth = native_states(source, offsets)
    fit = fit_fixed_bstar(times, truth, last_obs=fit_count, epoch_obs=-1,
                          bstar=fixed_bstar, lamda=1e-3, max_iter=35,
                          rms_epsilon=original_target, debug=False)
    assert fit.converged and fit.iterations < 35
    assert fit.sigmas[-1] < original_target
    assert fit.satellite.model.bstar == source.bstar == fixed_bstar
    assert all(step[6] == 0. for step in fit.steps)
    assert np.isfinite(fit.elements).all() and fit.elements[0] > 0
    assert np.isfinite(fit.covariance).all() and np.isfinite(fit.jacobian).all()

    # Independently recompute the original script's cost/N normalization and
    # weights, excluding its osculating seed observation at the fitted epoch.
    residual = truth - native_states(fit.satellite.model, offsets)
    variances = np.array([.01, .01, .01, .001, .001, .001])
    selected = np.arange(fit_count - 1)
    sigma = np.sqrt(np.sum((residual[selected].reshape(-1, 6) / variances)**2) / len(selected))
    assert sigma < original_target
    np.testing.assert_allclose(sigma, fit.sigmas[-1], rtol=1e-10, atol=0.)
    position_rms = np.sqrt(np.mean(np.sum(residual[:fit_count, 0]**2, axis=1)))
    assert position_rms < original_target * variances[0]  # original target implies <1 mm
    # The original target applies to fitting, not a newly invented 53-day
    # hold-out guarantee. Still propagate every withheld epoch and retain finite
    # six-state control coverage, without asserting real-data physical truth.
    assert len(residual[fit_count:]) == holdout_count
    assert np.isfinite(residual[fit_count:]).all()
